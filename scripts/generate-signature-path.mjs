// One-time generator: traces NOTE.signature through the site's actual
// Caveat font file (the same file the browser renders) and writes out
// real SVG path data for a stroke-draw ("handwriting") animation.
//
// Why this exists as a script instead of doing it at request time: the
// signature's letterforms don't change on their own, so there's no
// reason to ship opentype.js/wawoff2 (or spend a build step) on every
// visitor's machine just to re-derive the same path. Run this once
// whenever NOTE.signature or the Caveat font file changes:
//
//   node scripts/generate-signature-path.mjs
//
// It overwrites lib/signaturePath.ts, which the component imports as a
// plain static module — zero runtime cost, zero extra client JS.

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import wawoff2 from 'wawoff2';
import opentype from 'opentype.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');

const FONT_PATH = path.join(ROOT, 'app/fonts/caveat/caveat-latin-600-normal.woff2');
const OUTPUT_PATH = path.join(ROOT, 'lib/signaturePath.ts');
const TEXT = 'Phanindra'; // keep in sync with NOTE.signature in lib/content.ts
const FONT_SIZE = 200; // arbitrary trace-time size — the component scales the result to fit

// Straightforward SVG path formatter — opentype.js's own Path.toPathData()
// has a rounding-cache bug that occasionally emits a literal "NaN" into
// the string for specific decimal values (reproduced independently of
// any of our own math; verified the shifted command values themselves
// are all finite before formatting). Writing the ~15 lines by hand here
// avoids depending on that internal function entirely.
function fixed(n, decimals) {
  const f = 10 ** decimals;
  return (Math.round(n * f) / f).toString();
}
function commandsToPathData(commands, decimals) {
  let d = '';
  for (const c of commands) {
    if (c.type === 'M') d += `M${fixed(c.x, decimals)} ${fixed(c.y, decimals)} `;
    else if (c.type === 'L') d += `L${fixed(c.x, decimals)} ${fixed(c.y, decimals)} `;
    else if (c.type === 'Q') d += `Q${fixed(c.x1, decimals)} ${fixed(c.y1, decimals)} ${fixed(c.x, decimals)} ${fixed(c.y, decimals)} `;
    else if (c.type === 'C')
      d += `C${fixed(c.x1, decimals)} ${fixed(c.y1, decimals)} ${fixed(c.x2, decimals)} ${fixed(c.y2, decimals)} ${fixed(c.x, decimals)} ${fixed(c.y, decimals)} `;
    else if (c.type === 'Z') d += 'Z ';
  }
  return d.trim();
}

async function main() {
  const woff2Buffer = await readFile(FONT_PATH);
  const sfntBuffer = await wawoff2.decompress(woff2Buffer);
  const font = opentype.parse(sfntBuffer.buffer.slice(sfntBuffer.byteOffset, sfntBuffer.byteOffset + sfntBuffer.byteLength));

  const glyphPath = font.getPath(TEXT, 0, 0, FONT_SIZE);
  const bbox = glyphPath.getBoundingBox();

  // Normalize so the path's own bounding box starts at (0,0) — the
  // component sets the SVG viewBox from width/height below, so no
  // origin offset needs to live in the component.
  const dx = -bbox.x1;
  const dy = -bbox.y1;
  const width = bbox.x2 - bbox.x1;
  const height = bbox.y2 - bbox.y1;

  const shiftedCommands = glyphPath.commands.map((c) => {
    const out = { ...c };
    if ('x' in out) out.x += dx;
    if ('y' in out) out.y += dy;
    if ('x1' in out) out.x1 += dx;
    if ('y1' in out) out.y1 += dy;
    if ('x2' in out) out.x2 += dx;
    if ('y2' in out) out.y2 += dy;
    return out;
  });
  const d = commandsToPathData(shiftedCommands, 2);

  const fileContents = `// AUTO-GENERATED by scripts/generate-signature-path.mjs — do not hand-edit.
// Traced from app/fonts/caveat/caveat-latin-600-normal.woff2 at "${TEXT}".
// Regenerate with: node scripts/generate-signature-path.mjs

export const SIGNATURE_PATH = {
  d: ${JSON.stringify(d)},
  width: ${width.toFixed(2)},
  height: ${height.toFixed(2)},
  text: ${JSON.stringify(TEXT)},
};
`;

  await writeFile(OUTPUT_PATH, fileContents, 'utf8');
  console.log(`Wrote ${OUTPUT_PATH} (${width.toFixed(1)}×${height.toFixed(1)} units, ${glyphPath.commands.length} path commands)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
